"""Generate the offline browser catalog from the reviewed shared native catalog."""
import argparse
import json
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from crb.i18n.ui_translations import MESSAGES, TEMPLATES

def rendered():
    return '// Generated by release_tools/build_ui_catalog.py; do not edit.\nwindow.CRB_UI_CATALOG = ' + json.dumps({'messages': MESSAGES, 'templates': TEMPLATES}, ensure_ascii=False, separators=(',', ':')) + ';\n'
if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'web/i18n-catalog.js'
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != rendered():
            raise SystemExit('Browser UI catalog is out of date')
    else:
        target.write_text(rendered(), encoding='utf-8')
